"""Generate frontend transport types from the positional records in iCareX.Shared."""

from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SHARED = ROOT / "src" / "iCareX.Shared"
OUTPUTS = {"Identity": "auth-contracts.ts", "Vehicles": "vehicle-contracts.ts"}
SCALARS = {
    "string": "string", "Guid": "string", "DateOnly": "string",
    "DateTimeOffset": "string", "bool": "boolean", "int": "number",
    "long": "number", "decimal": "number", "double": "number",
}


def typescript_type(csharp: str) -> str:
    if csharp.endswith("?"):
        return typescript_type(csharp[:-1]) + " | null"
    if csharp.endswith("[]"):
        return "Array<" + typescript_type(csharp[:-2]) + ">"
    collection = re.fullmatch(r"(?:IReadOnlyCollection|IReadOnlyList|IEnumerable|List)<(.+)>", csharp)
    if collection:
        return "Array<" + typescript_type(collection[1]) + ">"
    if csharp in SCALARS:
        return SCALARS[csharp]
    if re.fullmatch(r"[A-Z][A-Za-z0-9]*", csharp):
        return csharp
    raise ValueError(f"Unsupported C# transport type: {csharp}")


def parameters(signature: str) -> list[str]:
    parts, start, depth = [], 0, 0
    for index, char in enumerate(signature):
        if char == "<":
            depth += 1
        elif char == ">":
            depth -= 1
        elif char == "," and depth == 0:
            parts.append(signature[start:index].strip())
            start = index + 1
    if signature[start:].strip():
        parts.append(signature[start:].strip())
    return parts


def generate(feature: str) -> str:
    blocks = ["// Generated by tools/contracts/generate_typescript.py; edit the C# DTOs instead."]
    names = set()
    for source in sorted((SHARED / "Contracts" / feature).glob("*.cs")):
        content = source.read_text(encoding="utf-8-sig")
        for match in re.finditer(r"public sealed record\s+(\w+)\s*\((.*?)\);", content, re.S):
            name, signature = match.groups()
            if name in names:
                raise ValueError(f"Duplicate transport type: {name}")
            names.add(name)
            fields = []
            for parameter in parameters(signature):
                field = re.fullmatch(r"(.+?)\s+(\w+)", parameter)
                if not field:
                    raise ValueError(f"Unsupported positional parameter: {parameter}")
                csharp, property_name = field.groups()
                property_name = property_name[0].lower() + property_name[1:]
                optional = "?" if csharp.endswith("?") else ""
                fields.append(f"  {property_name}{optional}: {typescript_type(csharp)}")
            blocks.append("export type " + name + " = {\n" + "\n".join(fields) + "\n}")
    if not names:
        raise ValueError(f"No positional record DTOs found for {feature}")
    return "\n\n".join(blocks) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated types are out of date.")
    args = parser.parse_args()
    outputs = {name: generate(feature) for feature, name in OUTPUTS.items()}
    outputs["index.ts"] = ''.join(f'export type * from "./{name[:-3]}"\n' for name in OUTPUTS.values())
    stale = []
    for name, content in outputs.items():
        path = SHARED / "typescript" / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        parser.exit(1, "Outdated shared contracts: " + ", ".join(stale) + "\n")
    print("Shared TypeScript contracts are current." if args.check else "Generated shared TypeScript contracts.")


if __name__ == "__main__":
    main()
